import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { chromium } from '@playwright/test';

const port = Number(process.env.FRONTEND_DEMO_PORT || 5187);
assert.ok(Number.isInteger(port) && port >= 1024 && port <= 65535);
const base = `http://127.0.0.1:${port}`;
const screenshots = '/tmp/squaretable-frontend-redesign';
await mkdir(screenshots, { recursive: true });
assert.equal((await fetch(`${base}/.env.beta`)).status, 404);
assert.equal((await fetch(`${base}/api/v1/characters`)).status, 404);
const browser = await chromium.launch({ headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [];
  const requests = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', request => requests.push(request.url()));
  await page.goto(base);
  await page.locator('.story-card').first().waitFor();
  assert.equal(await page.locator('.story-card').count(), 3);
  await page.locator('#search').fill('无此内容');
  assert.match(await page.locator('#results').innerText(), /没有找到/);
  await page.locator('[data-action=clear-filters]').click();
  await page.locator('[data-genre=奇幻]').click();
  assert.equal(await page.locator('.story-card').count(), 1);
  await page.locator('.favorite').click();
  assert.equal(await page.locator('.favorite').getAttribute('aria-pressed'), 'true');
  await page.locator('.card-link').click();
  await page.locator('[data-action=identity]').click();
  await page.locator('[name=name]').fill('验收旅人');
  await page.keyboard.press('Escape');
  await page.waitForFunction(() => !document.querySelector('#modal').open);
  assert.equal(await page.evaluate(() => document.activeElement?.dataset.action), 'identity');
  await page.locator('[data-action=identity]').click();
  await page.locator('[name=name]').fill('验收旅人');
  await page.locator('#identity-form button[type=submit]').click();
  await page.locator('#draft').waitFor();
  assert.match(await page.locator('.reader-head').innerText(), /验收旅人/);
  await page.locator('#draft').fill('我提起灯，询问信的来处。');
  await page.locator('#send').click();
  await page.waitForFunction(() => document.querySelectorAll('.message').length === 3 && document.querySelector('.message:last-child p').textContent.length > 0);
  await page.locator('#send').click();
  assert.match(await page.locator('#reader-status').innerText(), /已停止/);
  const partial = await page.locator('.message:last-child p').innerText();
  await page.waitForTimeout(200);
  assert.equal(await page.locator('.message:last-child p').innerText(), partial);
  await page.locator('#scenario').selectOption('failure');
  await page.locator('#draft').fill('失败时保留这段行动');
  await page.locator('#send').click();
  assert.match(await page.locator('#reader-status').innerText(), /失败/);
  assert.equal(await page.locator('#draft').inputValue(), '失败时保留这段行动');
  await page.locator('#scenario').selectOption('insufficient');
  assert.equal(await page.locator('#send').isDisabled(), true);
  assert.equal(await page.locator('#sidebar-balance').innerText(), '0.00');
  assert.equal(await page.locator('#draft').inputValue(), '失败时保留这段行动');
  await page.locator('#scenario').selectOption('normal');
  await page.locator('#send').click();
  await page.waitForFunction(() => document.querySelector('#reader-status').textContent.includes('已结束'));
  await page.locator('[data-action=settings]').click();
  await page.locator('[data-size="19"]').click();
  assert.equal(await page.locator('.reading-column').evaluate(element => getComputedStyle(element).fontSize), '19px');
  await page.keyboard.press('Escape');
  const currentReader = page.url().split('#')[1];
  await page.goto(`${base}/#library`);
  assert.equal(await page.locator('.library-list .continue').count(), 2);
  await page.locator('.library-list [data-action=continue]').first().click();
  await page.locator('#draft').waitFor();
  assert.equal(page.url().split('#')[1], currentReader);
  assert.match(await page.locator('#transcript').innerText(), /失败时保留这段行动/);
  await page.goto(`${base}/#discover`);
  await page.locator('[data-genre=全部]').click();
  await page.locator('#scenario').selectOption('empty');
  assert.match(await page.locator('#results').innerText(), /等待开场/);
  await page.locator('#scenario').selectOption('error');
  await page.locator('[data-action=reset-state]').click();
  assert.equal(await page.locator('.story-card').count(), 3);
  await page.reload();
  await page.locator('.story-card').first().waitFor();
  await page.locator('.favorite').first().click();
  await page.locator('[data-action=favorites]').click();
  assert.equal(await page.locator('.story-card').count(), 1);
  await page.locator('.favorite').click();
  assert.equal(await page.locator('.story-card').count(), 0);
  await page.locator('[data-action=clear-filters]').click();
  await page.reload();
  await page.locator('.story-card').first().waitFor();
  for (const [width, height] of [[390, 844], [768, 1024], [1440, 1000]]) {
    await page.setViewportSize({ width, height });
    for (const theme of ['dark', 'light']) {
      await page.evaluate(theme => { document.documentElement.dataset.theme = theme; }, theme);
      for (const [screen, selector] of [['discover', '.story-grid'], ['detail/0', '.detail-grid'], ['reader/1', '#draft'], ['library', '.library-list'], ['create', '#author-title'], ['account', '.account-amount']]) {
        await page.evaluate(screen => { location.hash = screen; }, screen);
        await page.locator(selector).waitFor();
        assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), `Overflow: ${width} ${theme} ${screen}`);
        await page.screenshot({ path: `${screenshots}/${screen.replace('/', '-')}-${width}-${theme}.png`, fullPage: true });
      }
      await page.evaluate(() => { location.hash = 'detail/1'; });
      await page.locator('[data-action=identity]').click();
      const box = await page.locator('#modal').boundingBox();
      assert.ok(box && box.x >= 0 && box.x + box.width <= width + 1);
      await page.screenshot({ path: `${screenshots}/identity-${width}-${theme}.png` });
      await page.keyboard.press('Escape');
    }
  }
  await page.evaluate(() => { location.hash = 'create'; });
  await page.locator('#author-title').fill('<img src=x onerror=alert(1)>');
  await page.locator('[data-action=preview]').click();
  assert.equal(await page.locator('#modal-content img').count(), 0);
  assert.match(await page.locator('#modal-title').innerText(), /<img/);
  await page.keyboard.press('Escape');
  await page.locator('#theme-toggle').click();
  assert.equal(await page.locator('html').getAttribute('data-theme'), 'dark');
  assert.deepEqual(errors, []);
  assert.ok(requests.every(url => url.startsWith(`${base}/`)), 'Unexpected external request');
  assert.ok(requests.every(url => !url.includes('/api/')), 'Demo must not call business APIs');
  console.info(`Frontend demo passed: search/filter/favorite, identity/focus, simulated send/stop/failure/balance, settings, empty/error, escaped preview, six pages plus dialog at 390/768/1440 light/dark. Screenshots: ${screenshots}. Fixtures only; not production acceptance. Reader checked: ${currentReader}`);
} finally {
  await browser.close();
}
