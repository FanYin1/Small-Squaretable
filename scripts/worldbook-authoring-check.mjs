import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { expect } from '@playwright/test';

export async function checkWorldbookAuthoring({ page, owner, sql, base, evidence, checks }) {
  const book = await owner.api('/worldbooks', { name: '用途往返验收资料', scope: 'global' });
  const card = await owner.api('/characters', { name: '用途验收角色', cardData: { first_mes: '', extensions: { world: book.name } } });
  await owner.api(`/characters/${card.id}/worldbooks/${book.id}`, { action: 'bind', expectedCharacterId: null }, 'PUT', 200);
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto(`${base}/worldbooks/${book.id}`);
  await page.getByRole('button', { name: '添加第一个条目', exact: true }).click();
  const form = page.locator('.entry-form');
  const field = label => form.locator('.el-form-item').filter({ has: page.locator('.el-form-item__label', { hasText: label }) });
  const purposeSelect = page.locator('.el-select').filter({ has: page.getByRole('combobox', { name: '资料用途', exact: true }) });
  await purposeSelect.click();
  await page.getByRole('option', { name: '常识与概念补充', exact: true }).click();
  await page.getByPlaceholder('输入世界书条目内容...').fill('AUTHORING_PRIVATE_KNOWLEDGE');
  await field('常驻（始终激活）').locator('.el-switch').click();
  await field('注入位置').locator('.el-select').click();
  await page.getByRole('option', { name: '增强上下文顶部', exact: true }).click();
  await field('Insertion Order').getByRole('spinbutton').fill('177');
  await page.getByRole('button', { name: '保存', exact: true }).click();
  await expect(form).toHaveCount(0);
  const entriesPath = `/worldbooks/${book.id}/entries`;
  let [entry] = await owner.api(entriesPath);
  assert.equal(entry.keyword, '');
  assert.equal(entry.position, 177);
  assert.equal(entry.settings.constant, true);
  assert.equal(entry.settings.position, 'ANTop');
  assert.equal(entry.settings.squaretablePurpose, 'knowledge');
  const createStory = () => owner.api('/chats', { characterId: card.id, clientRequestId: randomUUID() });
  const oldStory = await createStory();
  const content = async chatId => (await sql`SELECT snapshot FROM story_content WHERE chat_id = ${chatId}`)[0].snapshot;
  const worldbook = async chatId => (await sql`SELECT snapshot FROM story_worldbooks WHERE chat_id = ${chatId}`)[0].snapshot;
  assert.deepEqual((await content(oldStory.id)).characters[0].diagnostics.books.purposes, ['knowledge']);
  checks.push('Author creates a constant entry without keywords through the real UI; purpose, injection position and ordering persist');

  await page.getByRole('button', { name: '编辑条目', exact: true }).click();
  await purposeSelect.click();
  await page.getByRole('option', { name: '表达与风格', exact: true }).click();
  await page.screenshot({ path: `${evidence}/purpose-desktop.png`, fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
  await page.screenshot({ path: `${evidence}/purpose-mobile.png`, fullPage: true });
  await page.getByRole('button', { name: '保存', exact: true }).click();
  await expect(form).toHaveCount(0);
  await page.reload();
  await page.getByRole('button', { name: '编辑条目', exact: true }).click();
  await expect(purposeSelect).toContainText('表达与风格');
  const newStory = await createStory();
  assert.deepEqual((await content(oldStory.id)).characters[0].diagnostics.books.purposes, ['knowledge']);
  assert.deepEqual((await content(newStory.id)).characters[0].diagnostics.books.purposes, ['style']);
  assert.equal((await worldbook(oldStory.id)).bindings[0].books[0].entries[0].settings.squaretablePurpose, 'knowledge');
  checks.push('Purpose edit survives reload at desktop/mobile sizes; old story keeps knowledge and new story captures style');

  await owner.api(`${entriesPath}/${entry.id}`, { settings: { ...entry.settings, squaretablePurpose: 'foreign-purpose', selectiveLogic: 'NOT_ALL', role: 2, excludeRecursion: true }, recursive: false, preventRecursion: true }, 'PATCH', 200);
  await page.reload();
  await page.getByRole('button', { name: '编辑条目', exact: true }).click();
  await expect(form).toContainText('原声明：foreign-purpose（未识别）');
  await page.getByRole('button', { name: '保存', exact: true }).click();
  await expect(form).toHaveCount(0);
  [entry] = await owner.api(entriesPath);
  assert.equal(entry.settings.squaretablePurpose, 'foreign-purpose');
  assert.equal(entry.settings.selectiveLogic, 'NOT_ALL');
  const exported = await owner.api(`/worldbooks/${book.id}/export`);
  assert.equal(exported.entries[0].position, 2);
  assert.equal(exported.entries[0].extensions.role, 2);
  assert.equal(exported.entries[0].prevent_recursion, true);
  const imported = await owner.api('/worldbooks/import-file', exported);
  const [roundTrip] = await owner.api(`/worldbooks/${imported.worldBookId}/entries`);
  assert.equal(roundTrip.settings.squaretablePurpose, 'foreign-purpose');
  assert.equal(roundTrip.settings.selectiveLogic, 'NOT_ALL');
  assert.equal(roundTrip.settings.position, 'ANTop');
  assert.equal(roundTrip.recursive, false);
  assert.equal(roundTrip.preventRecursion, true);
  await owner.api(`/worldbooks/${imported.worldBookId}/import`, exported);
  const appended = await owner.api(`/worldbooks/${imported.worldBookId}/entries`);
  assert.equal(appended.length, 2);
  assert.deepEqual(appended[0].settings, appended[1].settings);
  await owner.api(`/worldbooks/${imported.worldBookId}/import`, { entries: [{ content: 'must not persist' }, { content: 2 }] }, 'POST', 400);
  assert.equal((await owner.api(`/worldbooks/${imported.worldBookId}/entries`)).length, 2);
  checks.push('Unknown purpose survives edit; export/import and append preserve purpose, position, logic, role and recursion; invalid append writes nothing');
  return { cardId: card.id, bookId: book.id, oldStoryId: oldStory.id, newStoryId: newStory.id, importedBookId: imported.worldBookId };
}
